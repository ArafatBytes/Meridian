-- ---------------------------------------------------------------------------
-- expires_at is derived, and callers cannot set it
-- ---------------------------------------------------------------------------
-- The same formula and the same 5.0 threshold as risk_flags and
-- community_clusters, and a third implementation of it for the same stated
-- reason: the three surfaces must be able to decay independently if one ever
-- needs a different threshold.
--
-- A BEFORE trigger rather than a GENERATED column because `timestamptz + interval`
-- is STABLE, not IMMUTABLE, so Postgres rejects it in a generation expression.

create or replace function public.news_crime_incidents_set_expires_at()
returns trigger
language plpgsql
as $function$
declare
    threshold constant double precision := 5.0;
    hours     double precision;
begin
    hours := new.half_life_hours
             * ln(greatest(new.severity_0, threshold) / threshold)
             / ln(2.0);

    new.expires_at := new.observed_at + make_interval(secs => hours * 3600.0);

    return new;
end;
$function$;

comment on function public.news_crime_incidents_set_expires_at() is
    'Derives news_crime_incidents.expires_at. Overwrites any supplied value -- the '
    'column is derived by contract, exactly as risk_flags.expires_at is.';

drop trigger if exists trg_news_crime_incidents_expires_at on public.news_crime_incidents;
create trigger trg_news_crime_incidents_expires_at
    before insert or update of observed_at, severity_0, half_life_hours
    on public.news_crime_incidents
    for each row execute function public.news_crime_incidents_set_expires_at();


