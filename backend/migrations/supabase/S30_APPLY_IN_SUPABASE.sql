-- ===========================================================================
-- extracted_crimes — what an LLM read out of one document, for the audit trail
-- ===========================================================================
-- The crime counterpart of `extracted_incidents`, and a separate table for a
-- concrete reason rather than symmetry: `extracted_incidents` cannot hold one.
-- Its `kind` CHECK lists the nine mobility kinds and nothing else, and its
-- `mobility_impact` is NOT NULL. A robbery has no kind in that vocabulary and no
-- mobility impact at all, so storing it there would mean widening the CHECK and
-- writing a false 'none' into a column that means "traffic was not affected" —
-- putting crime back inside the mobility vocabulary by the back door, which is the
-- single thing this whole design exists to avoid.
--
-- Same contract as its sibling: one row per (document, crime). `news_crime_id`
-- null plus a `discarded_reason` is the audit trail for "read but deliberately not
-- published", which is where the "discarded, never guessed" invariant is evidenced.

create table if not exists public.extracted_crimes (
    extraction_id         uuid        primary key default gen_random_uuid(),

    doc_id                text        not null
                              references public.raw_documents (doc_id) on delete cascade,

    category              text        not null,

    -- The extraction model's own English sentence. This is what the corroboration
    -- gate embeds, and it is the ONLY place the model's prose is kept: it never
    -- reaches a user, because `news_crime_incidents.statement` is built from the
    -- category, the publisher and the date by app/policy/attribution.py.
    summary_en            text        not null,

    -- The place name exactly as the article wrote it, unmodified, so the
    -- Geolocation Agent's accuracy number stays meaningful against real inputs.
    location_text         text        not null,

    extraction_confidence double precision not null,

    source                jsonb       not null,   -- SourceRef

    -- Set once this extraction has produced or joined a published incident.
    news_crime_id         uuid        references public.news_crime_incidents (incident_id)
                              on delete set null,

    discarded_reason      text,

    created_at            timestamptz not null default now(),

    constraint extracted_crimes_category_check
        check (category in (
            'theft', 'assault', 'harassment', 'vandalism',
            'burglary', 'robbery', 'fraud', 'other'
        )),

    constraint extracted_crimes_confidence_range
        check (extraction_confidence >= 0 and extraction_confidence <= 1),

    constraint extracted_crimes_discarded_reason_check
        check (discarded_reason is null or discarded_reason in (
            'unresolved_location', 'duplicate', 'rejected', 'low_confidence'
        )),

    -- A published extraction cannot also carry a discard reason. The reverse is
    -- allowed: both null means "extracted, not yet decided".
    constraint extracted_crimes_not_both_published_and_discarded
        check (news_crime_id is null or discarded_reason is null)
);

create index if not exists idx_extracted_crimes_doc_id
    on public.extracted_crimes (doc_id);
create index if not exists idx_extracted_crimes_news_crime_id
    on public.extracted_crimes (news_crime_id);
create index if not exists idx_extracted_crimes_created_at
    on public.extracted_crimes (created_at desc);

