-- ---------------------------------------------------------------------------
-- Refuse to run against a `journeys` this migration did not create
-- ---------------------------------------------------------------------------
-- `create table if not exists` is a silent no-op against an existing table, and
-- that silence is dangerous here: a `journeys` built by anything other than this
-- file has none of the constraints below, and the constraints ARE the state
-- machine. The invariant tests would still pass, because they read this file,
-- while the database enforced nothing.
--
-- That is not hypothetical. `app/core/database.py::init_db` runs
-- `Base.metadata.create_all` on every application start, and for as long as JG1
-- had a SQLAlchemy model the running development server created exactly such a
-- table -- varchar instead of text, no CHECKs, no foreign key, no partial unique
-- index, RLS off -- within a minute of the class being written. The model is
-- gone for that reason (see `app/models/journey.py`), and this guard is the
-- second half of the same fix: it turns a silent skip into a stop with a
-- sentence that says what to do.
--
-- `journeys_state_check` is the sentinel because nothing but this file creates
-- it.

do $guard$
begin
    if exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'journeys'
    ) and not exists (
        select 1 from pg_constraint where conname = 'journeys_state_check'
    ) then
        raise exception
            'public.journeys exists but was not created by this migration: it has no '
            'journeys_state_check, so none of JG1''s invariants are enforced. It was '
            'almost certainly built by Base.metadata.create_all on application start. '
            'Drop it (it holds no data worth keeping at that point) and run this '
            'migration again: drop table public.journeys;';
    end if;
end $guard$;


create table if not exists public.journeys (
    journey_id        uuid primary key default gen_random_uuid(),

    -- auth.users, not public.users. `public.users` is a mirror that is not
    -- reliably populated -- 20261010160000__gd_profiles_on_auth_users.sql is the
    -- migration that exists only because D08 got this wrong, and the account
    -- that had filed a report was not in it. Every user-owned table added since
    -- points here.
    user_id           uuid not null references auth.users (id) on delete cascade,

    -- active -> arrived | cancelled, and no other edge. See the CHECK below and
    -- app/models/journey.py, which carries the same three constants.
    state             text not null default 'active',

    -- geography, not geometry: metres on a sphere, which is what every caller
    -- wants. Same choice and same reason as risk_flags and community_clusters.
    origin            extensions.geography(Point, 4326) not null,
    destination       extensions.geography(Point, 4326) not null,

    -- What the person called the place. Whatever was in the destination field --
    -- a search result, a POI name from a map tap, or 'Selected Location' for a
    -- tap on open ground. It exists so a resumed journey can say "12 min to
    -- Mirpur" instead of showing coordinates, and that sentence is the entire
    -- visible output of this phase.
    destination_label text not null,

    -- ---- the chosen route, described rather than drawn --------------------

    -- The router's own id for the route that was chosen. Opaque to us, and not a
    -- foreign key: routes are computed per request and not stored, so this is a
    -- trace for reading logs against, not a reference that resolves.
    route_id          text,

    -- 'driving' or 'foot'. Stored because it changes the ETA by a factor of
    -- three or four, so a resume that re-routed on the wrong profile would
    -- silently move the deadline JG2 hangs on this row.
    route_profile     text not null,

    -- What the route promised when it was chosen, kept as-is. These are not
    -- updated on a re-route: they are what the person agreed to when they
    -- pressed Start, which is what JG2's deadline has to be derived from and
    -- what makes "it took twice as long as it said" answerable at all.
    distance_km       double precision not null,
    duration_minutes  double precision not null,

    -- 0-100, higher is safer. The only scale -- see RouteResponse.safety_score,
    -- where D06 deleted the two competing readings of it.
    safety_score      double precision,

    -- ---- the clock --------------------------------------------------------

    started_at        timestamptz not null default now(),

    -- An absolute instant, not a number of minutes. JG2's deadline slides this
    -- forward and a relative duration cannot be slid; it is also the only form
    -- that still means something after the phone has been off for ten minutes.
    -- Derived at insert from started_at + duration_minutes, by the endpoint.
    eta_at            timestamptz not null,

    -- When it reached a terminal state, by either route. Null while active, and
    -- the CHECK below makes that an invariant rather than a convention.
    ended_at          timestamptz,

    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),

    -- ---- invariants, at the level that cannot be bypassed ------------------

    -- Three states. JG2 adds `check_in_sent` and JG3 the rest of the escalation
    -- chain, each in its own migration, by altering this constraint. text +
    -- CHECK rather than a Postgres enum precisely so that is an ordinary ALTER
    -- inside a transaction -- same choice as risk_flags.kind.
    constraint journeys_state_check
        check (state in ('active', 'arrived', 'cancelled')),

    -- A journey has an end time if and only if it has ended. The shape of
    -- gd_drafts_approved_iff_ready and community_clusters_corroborated_iff_
    -- timestamped: a state that cannot be faked by writing one column.
    --
    -- This is the one that stops the JG2 failure mode where a journey reads
    -- `arrived` with no instant of arrival, leaving nothing to say whether the
    -- deadline was met.
    constraint journeys_ended_iff_terminal
        check ((state = 'active') = (ended_at is null)),

    constraint journeys_eta_after_start
        check (eta_at >= started_at),

    constraint journeys_ended_after_start
        check (ended_at is null or ended_at >= started_at),

    constraint journeys_profile_check
        check (route_profile in ('driving', 'foot')),

    constraint journeys_distance_sane
        check (distance_km >= 0),

    constraint journeys_duration_sane
        check (duration_minutes >= 0),

    constraint journeys_safety_range
        check (safety_score is null or (safety_score >= 0 and safety_score <= 100))
);


