-- ---------------------------------------------------------------------------
-- One open journey per person
-- ---------------------------------------------------------------------------
-- A partial unique index, so the database refuses a second active journey rather
-- than the endpoint remembering to.
--
-- It has to be enforced here because the client cannot be trusted to have ended
-- the last one: the force-stop this phase is built around is exactly the case
-- where an active row is left behind with nobody to close it. POST /journeys
-- cancels the existing active journey before inserting, and this index is what
-- makes a bug in that sequence a failed insert instead of two live journeys --
-- which from JG3 onward would mean two deadlines and two guardians watching one
-- person.

create unique index if not exists idx_journeys_one_active_per_user
    on public.journeys (user_id)
    where state = 'active';

-- The resume read: the caller's open journey, on launch.
create index if not exists idx_journeys_user_started
    on public.journeys (user_id, started_at desc);


-- ---------------------------------------------------------------------------
-- updated_at
-- ---------------------------------------------------------------------------
-- public.set_updated_at() is created by SCHEMA.sql. Guarded so this migration
-- still applies to a database where SCHEMA.sql has not run yet.

do $guard$
begin
    if exists (
        select 1 from pg_proc p
        join pg_namespace n on n.oid = p.pronamespace
        where n.nspname = 'public' and p.proname = 'set_updated_at'
    ) then
        drop trigger if exists trg_journeys_updated_at on public.journeys;
        create trigger trg_journeys_updated_at
            before update on public.journeys
            for each row execute function public.set_updated_at();
    end if;
end $guard$;


