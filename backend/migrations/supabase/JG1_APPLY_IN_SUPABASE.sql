-- ===========================================================================
-- 20261014150000__journeys
-- JG1 — the journey that survives
-- ===========================================================================
-- One table. A journey is "this person set off from here, heading there, at this
-- time, expecting to arrive by then, and here is how that ended."
--
-- B10 was one line in DEMO_PLAN.md and is seven phases in JOURNEY_GUARDIAN.md.
-- This is the first, and its whole claim is survival: the row outlives the
-- process. Force-stop the app mid-journey, reopen it, and the journey is still
-- there, because it was never in the screen.
--
-- NOTHING WATCHES THIS TABLE. There is no deadline column, no check-in, no
-- escalation state and no scheduled job reading it. Those are JG2 and JG3 and
-- they add their own columns in their own migrations. A deadline column written
-- now would be a column with no clock behind it, and the next person to read it
-- would reasonably assume there was one.
--
-- ---------------------------------------------------------------------------
-- Why there is no polyline in here
-- ---------------------------------------------------------------------------
-- The obvious column is the chosen route's geometry, so that resuming redraws
-- exactly what was on screen. It is the wrong column, for a reason that only
-- shows up on a real resume.
--
-- A journey is resumed minutes or tens of minutes after it started, from
-- wherever the person has got to. The stored polyline begins at an origin they
-- have left, so `useNavigation` would snap them to a point far behind and
-- narrate a turn they already took. The route has to be recomputed from the
-- present position regardless -- which is `recalculateFrom` in MapScreen, a path
-- that already exists and is already tested.
--
-- So what is stored is the *description* of what was chosen -- the profile, the
-- router's own id for it, and the numbers it promised -- and not its geometry.
-- That also keeps the row small: an `overview=full` polyline across Dhaka is a
-- few thousand coordinates, and a jsonb blob of them per journey is a storage
-- and retention surface bought for nothing.
--
-- The position log is the other thing deliberately absent. JOURNEY_GUARDIAN.md's
-- own note on this phase: "a log written from day one is a privacy surface with
-- no feature behind it yet." JG5 is the phase that wants history.
--
-- ---------------------------------------------------------------------------
-- Backend-only, like every table since B6a
-- ---------------------------------------------------------------------------
-- RLS on, no policies, so `anon` and `authenticated` cannot touch it through
-- PostgREST at all; the service role bypasses RLS. The app reaches it through
-- /api/v1/journeys/*, which is authenticated and scopes every query to the
-- caller.
--
-- That matters more here than for most tables. A client that could write this
-- one directly could insert a journey against another user's id -- and from JG3
-- onward a journey is what decides whose guardian gets told something. It could
-- also mark its own journey `arrived`, which from JG2 onward is how you stop a
-- deadline. Both of those are the feature working backwards.
--
-- Forward-only. Do not edit this file once applied anywhere.
-- ===========================================================================

