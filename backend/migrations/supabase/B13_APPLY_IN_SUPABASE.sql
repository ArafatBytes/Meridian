-- ---------------------------------------------------------------------------
-- Withdrawal: the one status transition a client may ask for
-- ---------------------------------------------------------------------------
-- `security definer` so it can write a column the caller has no privilege on,
-- and narrow enough that this is safe: it sets exactly one column to exactly one
-- value, only on a row the caller owns, and only from 'filed'.
--
-- This is the counterpart of corroboration. If your report can contribute to a
-- published cluster, you have to be able to pull it back out -- and that must
-- not mean deleting the row, because a cluster published partly on the strength
-- of your report is a claim whose provenance has to stay auditable.
--
-- `search_path` is pinned: a `security definer` function that resolves names
-- through the caller's path can be hijacked by a schema the caller controls.
create or replace function public.withdraw_crime_report(p_report_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
    v_updated integer;
begin
    if auth.uid() is null then
        raise exception 'withdraw_crime_report requires an authenticated caller';
    end if;

    update public.crime_reports
       set status = 'withdrawn',
           updated_at = now()
     where id = p_report_id
       and user_id = auth.uid()
       and status = 'filed';

    get diagnostics v_updated = row_count;
    return v_updated > 0;
end;
$function$;

comment on function public.withdraw_crime_report(uuid) is
    'Retract your own filed report. Returns false if it is not yours, does not '
    'exist, or is already withdrawn or removed. The only path by which a client '
    'may change crime_reports.status.';

revoke all on function public.withdraw_crime_report(uuid) from public;
grant execute on function public.withdraw_crime_report(uuid) to authenticated;

