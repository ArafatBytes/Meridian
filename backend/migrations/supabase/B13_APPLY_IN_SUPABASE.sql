-- ---------------------------------------------------------------------------
-- Visibility: your own reports only
-- ---------------------------------------------------------------------------
-- The old policy was `for select to authenticated using (true)` -- every
-- authenticated user could read every report ever filed, and MapScreen did
-- exactly that, unbounded in time and space.
--
-- One stranger's uncorroborated account naming a street is the "permanent area
-- label" the concept document (section 9) commits to never producing, and a pin
-- at a street corner plus a timestamp plus a narrative can identify a victim --
-- a different privacy surface from quoting a newspaper, governed by section 9
-- and the B14 retention registry.
--
-- So reports become private to their author, and the shared surface is fed only
-- by corroborated clusters, which carry counts rather than narratives. The
-- corroboration agent reads this table through DATABASE_URL as the service role,
-- which bypasses RLS, so tightening this does not blind it.
drop policy if exists "crime_reports_select_all" on public.crime_reports;
drop policy if exists "crime_reports_select_own" on public.crime_reports;
create policy "crime_reports_select_own" on public.crime_reports
    for select to authenticated using (auth.uid() = user_id);


-- ---------------------------------------------------------------------------
-- Column privileges: `status` is not the client's to write
-- ---------------------------------------------------------------------------
-- Revoke the table-level grant, then hand back exactly the content columns.
-- `authenticated` keeps INSERT and DELETE as before (both still governed by the
-- existing row policies); only UPDATE is narrowed.
--
-- `id`, `user_id` and `created_at` are withheld along with `status`: a client
-- that could rewrite `user_id` could move a report onto another account, and one
-- that could rewrite `created_at` could backdate a report into a corroboration
-- window it was not in.
