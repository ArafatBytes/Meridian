-- ===========================================================================
-- 20261013120000__report_trust
-- ===========================================================================
-- `crime_reports.status` was trying to be two things at once, and could be
-- neither. This migration splits them, deletes the half that was never true,
-- and closes a privilege hole the old design left open.
--
-- Forward-only. Do not edit this file once applied anywhere -- scripts/migrate.py
-- records a checksum and refuses to run if it changes.
--
-- ---------------------------------------------------------------------------
-- 1. What was wrong
-- ---------------------------------------------------------------------------
-- The old CHECK allowed ('pending', 'verified', 'investigating', 'resolved'),
-- which mixes two unrelated questions:
--
--   * a TRUST question  -- do we believe this enough to show it to strangers?
--     ('pending' -> 'verified')
--   * a CASEWORK question -- what is happening with the real-world incident?
--     ('investigating' -> 'resolved')
--
-- Both halves were dead. Nothing in the codebase has ever written any value but
-- the default: `app/api/v1/endpoints/crimes.py::verify_crime_report` is `pass`,
-- there is no role column on `users` to gate an admin on, and the two report
-- screens rendered a `verified` badge case and a tick that no code path could
-- produce. Every user saw "Pending" forever, next to a tick that was unreachable.
--
-- The casework half is also redundant: `gd_drafts` already owns that lifecycle
-- properly ('draft' -> 'ready_to_file', then gd_number and gd_filed_at), with
-- its own constraints, and it is the table that knows anything about it.
--
-- ---------------------------------------------------------------------------
-- 2. Why there is no "approve" state at all any more
-- ---------------------------------------------------------------------------
-- A moderator cannot verify that a crime occurred. They can only judge whether
-- the prose looks plausible. Stamping "Verified" on that judgement makes the
-- badge mean "someone thought this looked fine", which is worse than no badge,
-- because users will trust it.
--
-- So a report is never approved. Trust is not a property of one claim here --
-- it is a property of several independent claims agreeing, which is already how
-- this system decides what to believe about news (app/agents/rumour_guard.py,
-- and the risk_flags_confirmed_needs_two_sources CHECK). A corroborated
-- *cluster* of reports is published; a single report is not. That is the next
-- migration, 20261013120100__community_clusters.
--
-- The rule this leaves is: the machine promotes, a human only demotes. Nobody
-- needs to approve a claim for it to be removed, so the only human lever is
-- 'removed', which is exception-driven and fails in the safe direction.
--
-- ---------------------------------------------------------------------------
-- 3. The privilege hole
-- ---------------------------------------------------------------------------
-- `crime_reports_update_own` grants UPDATE on your own row, and `status` and
-- `verified` were columns on that row. The app ships the anon key, so three
-- lines of Supabase client code from any logged-in account self-awarded
-- verified = true:
--
--     await supabase.from('crime_reports')
--       .update({ status: 'verified', verified: true }).eq('id', myReportId);
--
-- RLS cannot stop that -- the row genuinely is yours. Column privileges can, and
-- they compose with RLS: Postgres checks both. So table-level UPDATE is revoked
-- from `authenticated` and granted back column by column, deliberately omitting
-- `status`. A client cannot name a column it has no privilege on, whatever RLS
-- says about the row.
--
-- The content columns are granted even though no screen edits a report today
-- (S08 may add one); `status` is the one that must never be client-writable.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- The new vocabulary
-- ---------------------------------------------------------------------------
-- Three states, and every one of them is reachable by code that exists:
--
--   filed      the report exists and is the author's own record. The default,
--              and what the corroboration agent counts.
--   withdrawn  the author retracted it. The row stays -- deleting it would
--              destroy the audit trail of a cluster that has already been
--              published -- but it stops counting toward corroboration.
--   removed    taken down (abuse, doxxing, a named individual, obvious
--              fabrication). The human lever, service-role only.
--
-- There is no 'resolved'. A report is a record of what someone said happened;
-- it does not resolve. The case does, and gd_drafts tracks that.

-- Existing rows first: the constraint cannot be swapped while rows violate it.
-- Everything in the table is 'pending', because nothing could ever write
-- anything else -- but the mapping is written out in full rather than assumed,
-- so this migration is also correct against a database somebody has poked by
-- hand. 'verified' collapses to 'filed' on purpose: the badge was never earned,
-- and carrying it forward would launder a claim this migration exists to retire.
alter table public.crime_reports
    drop constraint if exists crime_reports_status_check;

update public.crime_reports
   set status = 'filed'
 where status is distinct from 'filed';

alter table public.crime_reports
    alter column status set default 'filed';

alter table public.crime_reports
    add constraint crime_reports_status_check
        check (status in ('filed', 'withdrawn', 'removed'));

