-- ===========================================================================
-- 20261013120100__community_clusters
-- ===========================================================================
-- Where a corroborated group of user reports is published. The other half of
-- 20261013120000__report_trust: that migration established that a single report
-- is never approved, and this is what several independent reports can become.
--
-- Defect 54 / B13 / S29. The plan's own words: "The bridge is Rumour Guard's
-- existing logic applied to user reports: N independent reports, same area, same
-- window."
--
-- Forward-only. Do not edit this file once applied anywhere.
--
-- ---------------------------------------------------------------------------
-- Why this is not a row in `risk_flags`
-- ---------------------------------------------------------------------------
-- `risk_flags` is the obvious home and it is the wrong one, for a reason that
-- only shows up when you try to write the statement.
--
-- A risk flag is a *mobility* claim, and the product's vocabulary for one is
-- `MobilityImpact`: road_blocked, heavy_crowd, delay_likely, lane_closed,
-- impassable, none. All six are about traffic flow. A corner where three people
-- were robbed last week is not a road that is blocked, and `delay_likely` would
-- be a false statement about it.
--
-- `app/policy/framing.py` closes the other door. It bans `theft`, `robbery`,
-- `snatching`, `harassment`, `assault` and twenty more from any published flag
-- text, and says why in terms that apply exactly here:
--
--     "a user filing a report chooses a category, and the product repeats their
--      word back to them on their own report. A risk flag is the product's own
--      published claim about a place, and it does not get to say any of this."
--
-- So a report cluster could only enter `risk_flags` by inventing a kind, widening
-- `MobilityImpact`, and loosening the framing guard -- three changes to the one
-- table whose correctness this project has invested most in, to carry an object
-- with a different reliability model and a different privacy surface.
--
-- A sibling table reuses the *mechanism* -- dedup identity, corroboration count,
-- decay, derived expiry, a sweep -- without diluting the *contract*. Everything
-- below mirrors `risk_flags` deliberately, down to the constraint names, because
-- the next person to read it will already know that table.
--
-- ---------------------------------------------------------------------------
-- What a cluster is allowed to say
-- ---------------------------------------------------------------------------
-- A count and a recency, and nothing else:
--
--     "3 independent reports within 200 m in the last 6 days"
--
-- That states what the system knows. It does not say dangerous, does not name a
-- category, does not characterise anyone, and it names no individual. The
-- category stays on the author's own private report, where framing.py says it
-- belongs. `statement` is produced only by
-- `app/policy/community.py::to_cluster_statement`, which runs the same banned-term
-- guard the flag statements pass through -- one ban list, two producers.
--
-- The precedent is `app/scoring/chronic.py`, which puts real police crime
-- statistics on the map as a framed mobility claim and says of itself: "It is not
-- 'Dhaka is dangerous', and the framing guard would reject that sentence anyway."
--
-- ---------------------------------------------------------------------------
-- Backend-only, like `risk_flags`
-- ---------------------------------------------------------------------------
-- RLS on, no policies, so `anon` and `authenticated` cannot read or write it at
-- all; the service role bypasses RLS. The app reaches clusters through
-- GET /api/v1/risk/clusters.
--
-- That is not belt-and-braces. `severity_now` is computed on read, by decaying
-- `severity_0` to the instant asked about -- a client reading this table directly
-- would see the undecayed value and draw a cluster at full strength forever,
-- which is the one failure the whole decay design exists to prevent.
-- ===========================================================================

create schema if not exists extensions;
create extension if not exists postgis with schema extensions;


create table if not exists public.community_clusters (
    cluster_id       uuid primary key default gen_random_uuid(),

    -- Dedup identity, the way `risk_flags.event_key` is. Derived from the
    -- rounded centre and the category family, so the same corner producing more
    -- reports updates one cluster instead of accumulating near-duplicates.
    -- Assigned by `app/agents/report_corroboration.py`.
    cluster_key      text        not null unique,

    -- The report-category family this cluster was built from: 'violent',
    -- 'property' or 'other'. INTERNAL. It decides which reports may corroborate
    -- each other and it is never published -- the API shape has no field for it,
    -- because publishing it would be publishing the category by another name.
    family           text        not null,

    status           text        not null default 'provisional',

    -- geography, not geometry: metres on a sphere, which is what every caller
    -- wants. Same choice and same reason as risk_flags.
    location         extensions.geography(Point, 4326) not null,
    radius_m         integer     not null,

    -- How many reports, and how many distinct people filed them. The second is
    -- the one that decides anything: ten reports from one account are one
    -- account's claim. See `reporter_count` constraints below.
    report_count     integer     not null,
    reporter_count   integer     not null,

    -- One entry per contributing report: the report id, a per-cluster pseudonym
    -- for its author, and when the incident was. NO narrative, NO category, NO
    -- user id -- see the comment on the column.
    reports          jsonb       not null default '[]'::jsonb,

    -- Severity at observed_at, 0-100, derived from reporter_count by
    -- `app/policy/community.py::severity_for`. Never stored decayed, for the same
    -- reason risk_flags does not: every row would need rewriting on a timer.
    severity_0       double precision not null,

    half_life_hours  double precision not null,

    -- The most recent contributing report. A cluster that keeps attracting
    -- reports keeps refreshing, which is what makes it fade when the pattern
    -- stops rather than when the first report ages out.
    observed_at      timestamptz not null,

    -- The oldest contributing report, so the statement can say "in the last N
    -- days" from data instead of from a constant.
    first_report_at  timestamptz not null,

    -- DERIVED by trg_community_clusters_expires_at below, which overwrites
    -- whatever the caller supplied. Same contract as risk_flags.expires_at.
    expires_at       timestamptz not null,

    -- Written ONLY by app/policy/community.py::to_cluster_statement.
    statement        text        not null,

    -- When reporter_count first reached the corroboration threshold. A claim
    -- about our own process, not about the events -- the analogue of
    -- risk_flags.confirmed_at.
    corroborated_at  timestamptz,

    created_at       timestamptz not null default now(),
    updated_at       timestamptz not null default now(),

    -- ---- invariants, at the level that cannot be bypassed ------------------

    -- "Decay by default. No permanent area labels." Concept document section 9.
    -- A cluster is the object most at risk of becoming a permanent label on a
    -- neighbourhood, so this CHECK matters more here than it does on risk_flags.
    constraint community_clusters_half_life_positive
        check (half_life_hours > 0),

    -- THE headline invariant. One person's uncorroborated account never becomes
    -- a published claim about a place. This is the user-report analogue of
    -- risk_flags_confirmed_needs_two_sources, and it is enforced here as well as
    -- in the agent and in an invariant test for the same reason: it is the claim
    -- a judge is most likely to press on, and the strongest honest answer is that
    -- the database itself will not store the violation.
    constraint community_clusters_needs_two_reporters
        check (reporter_count >= 2),

    -- Two anonymous app accounts are not two newspapers, so the bar for the
    -- upper tier is higher than the two independent publishers risk_flags asks
    -- for. See app/policy/community.py for the thresholds and the reasoning.
    constraint community_clusters_corroborated_needs_three
        check (status <> 'corroborated' or reporter_count >= 3),

    -- Ten reports from two people is two people. The count of reports can exceed
    -- the count of reporters; it can never be smaller.
    constraint community_clusters_reporters_within_reports
        check (reporter_count <= report_count),

    -- A cluster cites one ReportRef per contributing report.
    constraint community_clusters_reports_match_count
        check (jsonb_array_length(reports) <= report_count),

    constraint community_clusters_status_check
        check (status in ('provisional', 'corroborated', 'expired', 'removed')),

    -- Corroboration has a timestamp, and neither can exist without the other.
    -- Same shape as gd_drafts_approved_iff_ready: what makes a state impossible
    -- to fake by writing one column.
    constraint community_clusters_corroborated_iff_timestamped
        check ((status = 'corroborated') = (corroborated_at is not null)),

    -- text + CHECK rather than a Postgres enum, so adding a family is an
    -- ordinary ALTER inside a transaction. Same choice as risk_flags.kind.
    constraint community_clusters_family_check
        check (family in ('violent', 'property', 'other')),

    constraint community_clusters_radius_sane
        check (radius_m > 0 and radius_m <= 2000),

    constraint community_clusters_severity_range
        check (severity_0 >= 0 and severity_0 <= 100),

    constraint community_clusters_window_ordered
        check (first_report_at <= observed_at)
);


