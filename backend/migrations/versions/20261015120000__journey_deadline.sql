-- ===========================================================================
-- 20261015120000__journey_deadline
-- JG2 — the deadline, and one tap to answer
-- ===========================================================================
-- JG1 gave a journey a row that survives the app being killed. This gives that
-- row a clock, and one question it is allowed to ask.
--
-- The claim of this phase: the server expects you by a time, and asks once when
-- you are not there. Nobody else is told. JG3 is the phase that widens the
-- circle, and the column `unanswered_at` below is the only thing this migration
-- adds for its benefit -- see the note on it.
--
-- ---------------------------------------------------------------------------
-- `eta_at` does not slide. `deadline_at` does.
-- ---------------------------------------------------------------------------
-- The JG1 migration's comment on `eta_at` said this phase would slide it
-- forward. That was wrong, and this migration corrects the comment rather than
-- honouring it.
--
-- `eta_at` is what the chosen route promised at the instant Start was pressed.
-- It belongs to the same group as `distance_km` and `duration_minutes`, which
-- JG1 states outright are never updated on a re-route, because they are what the
-- person agreed to and what makes "it took twice as long as it said" a question
-- with an answer. A column that is both the promise and the moving target can
-- answer neither question: once it has sled, there is nothing left that says
-- what was originally expected.
--
-- So `deadline_at` is a new column. It starts at the route's ETA plus a grace
-- period, it is editable at start, and it is the only thing that moves.
--
-- ---------------------------------------------------------------------------
-- What may move it, and the asymmetry that is the whole design
-- ---------------------------------------------------------------------------
-- Two things, and no third:
--
--   a heartbeat   the phone says "still going, about N seconds left"
--   an answer     the person taps "I'm fine" on the check-in
--
-- There is no code path that extends a deadline on its own, and that absence is
-- the feature. A phone in a jam talks; a phone in a ditch does not. Silence
-- therefore never buys an extension -- not because something checks for silence,
-- but because nothing happens without a request.
--
-- Once a check-in has been sent, heartbeats stop moving it. A phone whose GPS is
-- still ticking in a bag must not be able to talk its way out of a question that
-- a person has to answer.
--
-- ---------------------------------------------------------------------------
-- There is still no position anywhere in this table
-- ---------------------------------------------------------------------------
-- The heartbeat carries a number of seconds and nothing else. JG2 has no reader
-- for a location: the check-in goes to the person's own phone, and the only
-- message that needs a last known position is the escalation JG3 sends to
-- somebody else. Writing one now would be the privacy surface with no feature
-- behind it that JG1 refused for exactly the same reason.
--
-- Forward-only. Do not edit this file once applied anywhere.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- Refuse to run against a `journeys` this project's migrations did not create
-- ---------------------------------------------------------------------------
-- Same guard, same reason as 20261014150000__journeys.sql: `add column if not
-- exists` is a silent no-op, and `Base.metadata.create_all` on application start
-- has built a constraint-free `journeys` from a model once already. If the JG1
-- constraints are not here, the table is not the one this migration describes
-- and adding columns to it would produce something that looks applied and
-- enforces nothing.

do $guard$
begin
    if not exists (
        select 1 from pg_constraint where conname = 'journeys_state_check'
    ) then
        raise exception
            'public.journeys is missing journeys_state_check, so JG1''s migration '
            '(20261014150000__journeys.sql) has not been applied to this database -- '
            'or the table was built by something else, most likely '
            'Base.metadata.create_all on application start. Apply JG1 first. If a '
            'constraint-free journeys table is in the way: drop table public.journeys;';
    end if;
end $guard$;


-- ---------------------------------------------------------------------------
-- The clock
-- ---------------------------------------------------------------------------

-- When we expect you, and the instant the question gets asked.
--
-- Nullable only for the length of this migration: the backfill below fills every
-- existing row and the NOT NULL goes on afterwards. Doing it in that order means
-- the migration applies to a database that already has live journeys, which at
-- the time of writing is the developer's own.
alter table public.journeys
    add column if not exists deadline_at timestamptz;

-- Every journey written before this phase gets the deadline it would have been
-- given: its route's ETA plus the grace period. `app/journeys/deadline.py` holds
-- the same ten minutes, and `tests/invariants/test_journey_deadline.py` reads
-- both and asserts they agree -- a grace period that differs between the
-- backfill and the code would make old journeys behave unlike new ones with
-- nothing to say why.
update public.journeys
   set deadline_at = eta_at + interval '10 minutes'
 where deadline_at is null;

alter table public.journeys
    alter column deadline_at set not null;


-- When the phone last spoke. Null until it does.
--
-- Read by nothing in JG2 except the walkthrough, which is the point: it is how
-- you tell "the deadline did not move because the phone is silent" from "the
-- deadline did not move because the heartbeat is broken", and those two look
-- identical from the outside. JG5's "signals better than off-route" is what
-- turns it into a decision.
alter table public.journeys
    add column if not exists last_heartbeat_at timestamptz;


-- ---------------------------------------------------------------------------
-- The first two states of the escalation machine
-- ---------------------------------------------------------------------------
-- `normal` -> `check_in_sent` -> `normal`, and no further edge exists yet.
--
-- JG3 adds `contacts_notified` and `full_sos` by altering the CHECK below, which
-- is an ordinary ALTER inside a transaction precisely because this is text plus
-- a constraint rather than a Postgres enum -- the same choice, for the same
-- reason, as `journeys.state` and `risk_flags.kind`.
--
-- This is deliberately a *second* state column rather than more values in
-- `journeys.state`. A journey that is being asked a question is still active:
-- it has not arrived and it has not been cancelled, and collapsing the two
-- would mean every query that asks "is this journey running" has to know the
-- escalation vocabulary. `state` is where the journey is; `escalation_state` is
-- how worried we are about it.
alter table public.journeys
    add column if not exists escalation_state text not null default 'normal';

-- When we asked. Set each time the question is asked, so it is the *current*
-- ask rather than the first one.
alter table public.journeys
    add column if not exists check_in_sent_at timestamptz;

-- When they answered. Compared against `check_in_sent_at` rather than read on
-- its own: a journey that was asked at 10:40, answered at 10:41, and asked again
-- at 10:56 has an `answered_at` that is real and is about the previous question.
alter table public.journeys
    add column if not exists answered_at timestamptz;

-- The recorded non-response, which is what JG2 exists to produce and what JG3
-- is not allowed to escalate without.
--
-- Written by the sweep, once, when a check-in has gone unanswered past its
-- window -- never by a client, and never inferred at read time. The concept
-- document's rule for the escalation chain is that "every step past the first
-- requires a recorded non-response with a timestamp", and a condition evaluated
-- freshly on each read is not a record: it changes when the clock changes, it
-- leaves nothing behind to audit, and it cannot say *when* the system decided
-- somebody was not answering.
--
-- Cleared when a new question is asked, because it belongs to one ask.
--
-- JG2 writes it and reads it nowhere. That is the one exception this phase makes
-- to JG1's rule against columns with no feature behind them, and it is narrow
-- for a reason: the thing with no reader here is not a *capability* that might
-- never arrive, it is the output of a sweep branch that runs every minute and
-- that the walkthrough checks by hand.
alter table public.journeys
    add column if not exists unanswered_at timestamptz;


-- ---------------------------------------------------------------------------
-- Invariants, at the level that cannot be bypassed
-- ---------------------------------------------------------------------------
-- `add constraint if not exists` does not exist in Postgres, so each one is
-- guarded by name. Same shape as the trigger guard in JG1's migration.

do $c$
begin
    if not exists (select 1 from pg_constraint where conname = 'journeys_escalation_check') then
        alter table public.journeys add constraint journeys_escalation_check
            check (escalation_state in ('normal', 'check_in_sent'));
    end if;

    -- A journey cannot be waiting for an answer to a question nobody asked.
    -- One-directional, not a biconditional: after an answer the state returns to
    -- `normal` and `check_in_sent_at` stays, because it is the history of what
    -- happened on this trip and JG3's escalation reads it.
    if not exists (select 1 from pg_constraint where conname = 'journeys_asked_before_waiting') then
        alter table public.journeys add constraint journeys_asked_before_waiting
            check (escalation_state <> 'check_in_sent' or check_in_sent_at is not null);
    end if;

    -- You cannot answer before you were asked. This is the one that stops a
    -- client from writing an answer onto a journey that was never questioned and
    -- thereby buying itself an extension.
    if not exists (select 1 from pg_constraint where conname = 'journeys_answered_after_asked') then
        alter table public.journeys add constraint journeys_answered_after_asked
            check (
                answered_at is null
                or (check_in_sent_at is not null and answered_at >= check_in_sent_at)
            );
    end if;

    -- The same rule for the non-response, and it matters more: JG3 escalates on
    -- `unanswered_at`, so a row carrying one without a question behind it would
    -- be an escalation with no recorded cause.
    if not exists (select 1 from pg_constraint where conname = 'journeys_unanswered_after_asked') then
        alter table public.journeys add constraint journeys_unanswered_after_asked
            check (
                unanswered_at is null
                or (check_in_sent_at is not null and unanswered_at >= check_in_sent_at)
            );
    end if;

    -- A deadline before the journey began is not a deadline, it is a journey
    -- that was already late when it started.
    if not exists (select 1 from pg_constraint where conname = 'journeys_deadline_after_start') then
        alter table public.journeys add constraint journeys_deadline_after_start
            check (deadline_at >= started_at);
    end if;
end $c$;


-- ---------------------------------------------------------------------------
-- The sweep's own index
-- ---------------------------------------------------------------------------
-- `journey_watch` runs every minute and asks one question: which active
-- journeys are due something? Partial on `state = 'active'`, because a finished
-- journey is never due anything again and the table is mostly finished journeys
-- within a week of launch.

create index if not exists idx_journeys_due
    on public.journeys (deadline_at)
    where state = 'active';


comment on column public.journeys.eta_at is
    'What the chosen route promised when Start was pressed. Frozen -- it is not '
    'updated on a re-route and it is NOT the deadline. See deadline_at. (The JG1 '
    'comment here said JG2 would slide this; 20261015120000__journey_deadline.sql '
    'corrected that.)';

comment on column public.journeys.deadline_at is
    'JG2. When the server expects you. Starts at the route ETA plus grace, '
    'editable at start, and moved only by a heartbeat or an answer -- silence '
    'never extends it.';

comment on column public.journeys.unanswered_at is
    'JG2. When the sweep observed a check-in go unanswered past its window. The '
    'recorded non-response the escalation chain is not allowed to act without.';
