-- ===========================================================================
-- 20261015140000__journey_leash
-- JG2 — the chosen leash survives the heartbeat
-- ===========================================================================
-- A bug fix, found the first time JG2 was run on a phone, and the kind that is
-- worth a migration of its own rather than an edit to the one before it.
--
-- ---------------------------------------------------------------------------
-- What happened
-- ---------------------------------------------------------------------------
-- Someone started a three-minute walk, chose the `2 min` chip, and watched the
-- row:
--
--   19:45:53  started          deadline_at = 19:47:53     correct, +2 min
--   19:47:31  first heartbeat  deadline_at = 19:57:31     +11.6 min
--
-- The heartbeat proposed `now + remaining + GRACE`, which is ten minutes of
-- grace on top of whatever the route had left, and `greatest()` took it because
-- it was later. Sixty seconds after asking to be checked on in two minutes, they
-- had been given twelve -- silently, with nothing on the screen to say so, and
-- the check-in they were waiting for never came.
--
-- That is the feature working backwards. The grace period exists because the
-- router does not know she is stopping for food; it has no business overriding
-- her when she has said how long she is willing to be unwatched. §6 of
-- JOURNEY_GUARDIAN.md is an entire feature built on that sentence -- "one button
-- that shortens the leash to minutes" -- and this bug would have made it a
-- button that does nothing a minute later.
--
-- ---------------------------------------------------------------------------
-- Why it needs a column
-- ---------------------------------------------------------------------------
-- The choice cannot be recovered from the row after the fact. `deadline_at -
-- started_at` was the leash at insert, and `deadline_at` is precisely the thing
-- a heartbeat overwrites -- so by the time the question is asked, the answer has
-- been destroyed by the mechanism that needed it.
--
-- ---------------------------------------------------------------------------
-- What the heartbeat does now
-- ---------------------------------------------------------------------------
--   deadline = greatest(deadline, now + least(remaining + GRACE, leash))
--              capped at started_at + MAX_DEADLINE
--
-- * no leash  -> `least` has nothing to cap against, the proposal stands, and
--                the behaviour is exactly what it was. This is the Route ETA
--                chip, which is the default and the common case.
-- * 2 min     -> each heartbeat renews two minutes from now. Reporting still
--                slides the clock, which is the design; it just slides it by
--                what she asked for.
-- * 1 hr      -> the initial deadline is already an hour out and `greatest`
--                keeps it there, so a tighter proposal from the route cannot
--                pull it in.
--
-- NULL still means "derive it from the route", not "no limit". The difference
-- matters: a NULL that meant unlimited would make the default chip the one with
-- no ceiling, which is the opposite of the intent.
--
-- Forward-only. Do not edit this file once applied anywhere.
-- ===========================================================================


do $guard$
begin
    if not exists (
        select 1 from pg_constraint where conname = 'journeys_escalation_check'
    ) then
        raise exception
            'public.journeys has no journeys_escalation_check, so '
            '20261015120000__journey_deadline.sql has not been applied to this '
            'database. Apply it first; this migration fixes a bug in it.';
    end if;
end $guard$;


-- How long this journey may go unheard-from, in seconds, when the person said
-- so at start. NULL means they accepted the route's own ETA and the heartbeat
-- derives it from what is left of the route.
--
-- Seconds rather than an interval so the endpoint can pass it as the same kind
-- of number it passes everywhere else -- `make_interval(secs => ...)` is the
-- idiom in this table already, and one representation beats two.
alter table public.journeys
    add column if not exists leash_seconds double precision;


do $c$
begin
    -- A leash shorter than MIN_DEADLINE could put the next deadline in the past
    -- on a slow heartbeat; one longer than MAX_DEADLINE would outrank the
    -- ceiling. Both are clamped in `journeys/deadline.py::leash` before they get
    -- here, and this is the backstop that makes that a guarantee rather than a
    -- convention.
    if not exists (select 1 from pg_constraint where conname = 'journeys_leash_sane') then
        alter table public.journeys add constraint journeys_leash_sane
            check (leash_seconds is null or (leash_seconds >= 120 and leash_seconds <= 21600));
    end if;
end $c$;


-- Existing rows keep NULL, which is the correct answer for every one of them:
-- they were written before this column existed, so nobody chose anything, and
-- deriving a leash from a deadline a heartbeat may already have moved would be
-- inventing a choice that was never made.


comment on column public.journeys.leash_seconds is
    'JG2. How long this journey may go unheard-from, when chosen at start. NULL '
    'means "derive it from what is left of the route". Caps what a heartbeat may '
    'propose -- see 20261015140000__journey_leash.sql.';
