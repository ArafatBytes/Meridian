-- ===========================================================================
-- Defect 9 — drop the `public.users` mirror
-- ===========================================================================
-- ADR 0003 proposed collapsing three user tables into one: `auth.users` is
-- identity, `public.profiles` is the only profile table, `public.users` goes.
-- Most of that is already true and happened piecemeal without the box being
-- ticked. This is the last step.
--
-- ## Why this is safe, checked rather than assumed
--
-- **Nothing references it.** Every user_id column in the schema targets
-- `auth.users(id)` directly, and always has:
--
--   crime_reports.user_id       -> auth.users(id)   SCHEMA.sql:84
--   emergency_contacts.user_id  -> auth.users(id)   SCHEMA.sql:126
--   sos_hot_words.user_id       -> auth.users(id)   SCHEMA.sql:155
--   sos_incidents.user_id       -> auth.users(id)   SCHEMA.sql:205
--   user_locations.user_id      -> auth.users(id)   SCHEMA.sql:234
--
-- The one genuine dependent was `gd_drafts.user_id`, and migration
-- `20261010160000__gd_profiles_on_auth_users.sql` repointed it at `auth.users`
-- for exactly this reason -- an account that can file a report must be able to
-- draft a GD from it, and the mirror was not reliably populated.
--
-- Section 3 below **verifies** that rather than trusting this comment, and
-- aborts if a dependent has appeared since.
--
-- **Nothing reads it.** The two columns anything ever read were `full_name` and
-- `phone`, both read by the GD form, which moved to `gd_profiles` in the same
-- October migration. `hot_words` on this table had zero readers in any branch:
-- B8 reads `public.sos_hot_words`. `password_hash` was always the literal string
-- `'supabase_managed'` -- Supabase owns authentication, `decode_token` verifies
-- its JWTs through JWKS, and `verify_password` is imported by
-- `endpoints/auth.py` and never called.
--
-- **Nothing writes it any more.** Until today, `endpoints/sos.py` auto-created
-- a row here on a user's first SOS. That block is deleted. It was not supplying
-- referential integrity -- the keys pointed elsewhere -- it was supplying a
-- display name for the alert email, and it supplied a bad one:
-- `full_name = email.split("@")[0]`, so an emergency contact was told to call
-- `nakib1990saleh`. The name now comes from `profiles.name`, which the user
-- typed and can edit.
--
-- ## The code change is a prerequisite, not a companion
--
-- `app/core/database.py:init_db()` runs `Base.metadata.create_all` on **every
-- API start**, inside a try/except that logs "Database not available" and
-- continues. While `app/models/user.py` existed, running this migration and
-- restarting the API would have **recreated the table**, and the swallowed
-- exception would have hidden the reason. `models/user.py` is deleted in the
-- same change as this file. Apply this against a build that has it.
--
-- ## Why 160000 and not 120000
--
-- The obvious timestamp was taken. `migrate.py status` reported this file as
-- `CHANGED` against ledger version `20261015120000` = `journey_deadline`,
-- applied `by=nakib` on 14 Oct, **with no file in this repository**. There is a
-- second, `20261015140000` = `journey_leash`, same situation, plus
-- `20261014150000` = `journeys`.
--
-- That is not a near miss. `migrate.py up` applies by version, so had this kept
-- `20261015120000` the runner would have treated it as already applied and
-- **skipped it forever** -- the schema change never runs and the ledger says it
-- did, which is exactly the failure defect 55 was about. The checksum mismatch
-- is what surfaced it.
--
-- Three hand-applied migrations with no committed files is the Journey Guardian
-- work (B10) in progress on the shared database. Leave it alone: do not drop
-- `journeys`, and do not build on its shape.
--
-- ## What is lost
--
-- Two rows of duplicated display data (`full_name`, `phone`, `email`) whose
-- authoritative copies are in `auth.users` and `public.profiles`. One of the two
-- `full_name` values is an email local part this project generated by accident
-- and is the defect itself. Nothing here is a record of anything that happened.
-- Section 1 prints what is about to go, so the ledger has it.
-- ===========================================================================


-- ---------------------------------------------------------------------------
-- 1. Say what is being destroyed, before destroying it
-- ---------------------------------------------------------------------------
do $$
declare
    n bigint;
    r record;
begin
    if not exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'users'
    ) then
        raise notice 'public.users does not exist -- already dropped. Nothing to do.';
        return;
    end if;

    select count(*) into n from public.users;
    raise notice 'public.users holds % row(s), about to be dropped:', n;

    for r in select id, email, full_name from public.users order by created_at loop
        raise notice '  % | % | full_name=%', r.id, r.email, r.full_name;
    end loop;
end $$;


-- ---------------------------------------------------------------------------
-- 2. Nobody should lose a profile they had typed
-- ---------------------------------------------------------------------------
-- A belt-and-braces carry-over. `profiles` is written at registration so this
-- is expected to insert nothing, but if an account somehow has a mirror row and
-- no profile, the mirror is the only copy of its display name and dropping the
-- table would destroy it. Only rows with a real auth user can move.
--
-- `full_name` is NOT NULL on the mirror, so there is always something to carry;
-- it may be the derived email local part, which is no worse than the absence it
-- would otherwise leave and is editable in the app.
insert into public.profiles (id, email, name, phone)
select u.id, u.email, u.full_name, nullif(u.phone, 'N/A')
from public.users u
join auth.users a on a.id = u.id
where not exists (select 1 from public.profiles p where p.id = u.id)
on conflict (id) do nothing;


-- ---------------------------------------------------------------------------
-- 3. Refuse to drop it if anything still points at it
-- ---------------------------------------------------------------------------
-- The claim this migration rests on is "no foreign key references
-- public.users". That was true when it was written. `drop table ... restrict`
-- would fail on a dependent, but with a confusing message, so this checks first
-- and names what it found -- a teammate's uncommitted migration is exactly the
-- kind of thing that appears between writing this and running it, and the
-- `journeys` table is the precedent for that happening here.
do $$
declare
    offenders text;
begin
    if not exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'users'
    ) then
        return;
    end if;

    select string_agg(
               format('%s.%s -> %s', c.conrelid::regclass, a.attname, c.conname),
               ', '
           )
      into offenders
      from pg_constraint c
      join unnest(c.conkey) as k(attnum) on true
      join pg_attribute a on a.attrelid = c.conrelid and a.attnum = k.attnum
     where c.contype = 'f'
       and c.confrelid = 'public.users'::regclass;

    if offenders is not null then
        raise exception
            'public.users still has dependent foreign keys: %. '
            'Repoint them at auth.users(id) first -- see migration '
            '20261010160000 for how gd_drafts was moved. Nothing was dropped.',
            offenders;
    end if;
end $$;


-- ---------------------------------------------------------------------------
-- 4. Drop it
-- ---------------------------------------------------------------------------
-- `restrict`, not `cascade`. Section 3 has already established there is nothing
-- to cascade to, so `cascade` could only ever silently destroy something that
-- appeared in between -- which is the one outcome worth refusing.
drop trigger if exists trg_users_updated_at on public.users;
drop table if exists public.users restrict;


-- ---------------------------------------------------------------------------
-- 5. Prove it
-- ---------------------------------------------------------------------------
do $$
begin
    if exists (
        select 1 from information_schema.tables
        where table_schema = 'public' and table_name = 'users'
    ) then
        raise exception 'public.users still exists after the drop';
    end if;
    raise notice 'OK: public.users is gone. Identity is auth.users; display data is public.profiles.';
end $$;
