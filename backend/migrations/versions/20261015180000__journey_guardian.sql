-- ===========================================================================
-- 20261015180000__journey_guardian
-- JG3 — someone else knows
-- ===========================================================================
-- The second person. JG1 made a journey survive, JG2 made the server notice
-- you were late and ask once; this is the phase where somebody other than you
-- is told. See JG3_PLAN.md, written before this file.
--
-- ---------------------------------------------------------------------------
-- The guardian is chosen per journey, not per account
-- ---------------------------------------------------------------------------
-- `guardian_contact_id` lives on the journey and is nullable. Two reasons, and
-- the nullability is the more important of them:
--
-- * Who should be told depends on the trip. The person you want told about a
--   2am ride home is not necessarily the one for a Tuesday commute, and a
--   profile setting makes the common case wrong half the time.
-- * **NULL is a valid journey, not a degraded one.** It is JG2's behaviour
--   exactly: the deadline runs, the check-in arrives, nobody else hears
--   anything. Somebody with no contacts saved, or who does not want a person
--   involved tonight, must still get the whole feature. A column that forced a
--   guardian would make the private case unusable.
--
-- It references `public.emergency_contacts(id)` rather than copying the name
-- and email onto the journey. A contact that is edited should be edited
-- everywhere, and a contact that is deleted should not leave a journey pointing
-- at an address nobody can see any more -- hence `on delete set null`, which
-- turns a deleted contact into "no guardian" rather than a dangling id or a
-- blocked delete.
--
-- ---------------------------------------------------------------------------
-- The escalation machine, widened from two states to five
-- ---------------------------------------------------------------------------
--   normal -> check_in_sent -> check_in_repeated -> contacts_notified -> full_sos
--      ^           |                  |                    |                |
--      +-----------+------------------+--------------------+----------------+
--                   an answer returns to normal from any state
--
-- JG2 chose `text + CHECK` over a Postgres enum for exactly this moment: adding
-- three state names is an ordinary `ALTER` inside a transaction, where
-- `ALTER TYPE ... ADD VALUE` could not have run in one.
--
-- Every forward edge gets a timestamp column, and every timestamp gets a CHECK
-- saying the step before it happened. That is the invariant from
-- IMPLEMENTATION_PLAN.md B10/S22-S23 and the promise in JOURNEY_GUARDIAN.md §7
-- -- *"Every step past the first requires a recorded non-response with a
-- timestamp. It cannot jump to panic."*
--
-- The ordering rules are enforced **here**, not only in the sweep that writes
-- them. A bug that skipped a step would then be an IntegrityError instead of an
-- email to somebody's mother, and the difference between those two outcomes is
-- the whole reason this product can be trusted with the feature.
--
-- ---------------------------------------------------------------------------
-- One position, and why this file is allowed to add one
-- ---------------------------------------------------------------------------
-- JG2 stored no position at all, deliberately, and
-- `test_the_heartbeat_carries_no_position` held the line with this reasoning:
-- *"the only message that needs a last known position is the escalation JG3
-- sends to somebody else, and a location written before there is anything to
-- read it is a privacy surface with no feature behind it."*
--
-- JG3 is that reader, so the position arrives with its first consumer and not
-- before. Two rules keep it honest:
--
-- * **One point, overwritten.** Not a log. JOURNEY_GUARDIAN.md JG1 already
--   decided this -- *"the log is only needed once JG5 wants history"* -- and JG5
--   is not being built, so a log would again be a surface with no reader.
-- * **Collected only when a guardian exists.** Enforced in the app at the point
--   of collection, because a privacy rule applied only at the point of use is
--   one refactor away from not being applied at all.
--
-- Forward-only. Do not edit this file once applied anywhere.
-- ===========================================================================


do $guard$
begin
    if not exists (
        select 1 from pg_constraint where conname = 'journeys_escalation_check'
    ) then
        raise exception
            'public.journeys has no journeys_escalation_check, so '
            '20261015120000__journey_deadline.sql has not been applied to this '
            'database. Apply it and 20261015140000__journey_leash.sql first.';
    end if;

    if not exists (
        select 1 from information_schema.columns
         where table_schema = 'public' and table_name = 'journeys'
           and column_name = 'leash_seconds'
    ) then
        raise exception
            'public.journeys has no leash_seconds, so '
            '20261015140000__journey_leash.sql has not been applied. Apply it '
            'first; this migration assumes the heartbeat respects the leash.';
    end if;

    if not exists (
        select 1 from information_schema.tables
         where table_schema = 'public' and table_name = 'emergency_contacts'
    ) then
        raise exception
            'public.emergency_contacts does not exist, and the guardian is a '
            'reference to it. Nothing in JG3 works without it.';
    end if;
end $guard$;


-- ---------------------------------------------------------------------------
-- The guardian
-- ---------------------------------------------------------------------------

alter table public.journeys
    add column if not exists guardian_contact_id uuid;

do $c$
begin
    -- Added separately from the column so a re-run is a no-op either way, and
    -- `on delete set null` so deleting a contact cannot block itself on an old
    -- journey or leave one pointing at an address that no longer exists.
    if not exists (
        select 1 from pg_constraint where conname = 'journeys_guardian_contact_fk'
    ) then
        alter table public.journeys add constraint journeys_guardian_contact_fk
            foreign key (guardian_contact_id)
            references public.emergency_contacts(id) on delete set null;
    end if;
end $c$;


-- ---------------------------------------------------------------------------
-- What was said, and when
-- ---------------------------------------------------------------------------
-- Six timestamps rather than an events table. They are the whole history this
-- phase needs, the journey screen renders them as a timeline, and a row that
-- carries its own story cannot drift from a log that carries a different one.

alter table public.journeys
    -- The two calm messages. Neither carries a location.
    add column if not exists started_notice_at    timestamptz,
    add column if not exists arrived_notice_at    timestamptz,
    -- The three escalation steps.
    add column if not exists check_in_repeated_at timestamptz,
    add column if not exists contacts_notified_at timestamptz,
    add column if not exists full_sos_at          timestamptz,
    -- The last point the phone reported, and when. Written by the heartbeat,
    -- read only by an escalation message.
    add column if not exists last_position        extensions.geography,
    add column if not exists last_position_at     timestamptz;


-- ---------------------------------------------------------------------------
-- The escalation machine
-- ---------------------------------------------------------------------------

do $c$
begin
    -- Replaced rather than widened: a CHECK cannot be altered in place, and
    -- dropping then adding inside one transaction means no window exists in
    -- which the column is unconstrained.
    if exists (select 1 from pg_constraint where conname = 'journeys_escalation_check') then
        alter table public.journeys drop constraint journeys_escalation_check;
    end if;
    alter table public.journeys add constraint journeys_escalation_check
        check (escalation_state in (
            'normal', 'check_in_sent', 'check_in_repeated',
            'contacts_notified', 'full_sos'
        ));
end $c$;


do $c$
begin
    -- Each state must have its own timestamp. The pattern JG2 set with
    -- `journeys_asked_before_waiting`, one state per rule rather than one big
    -- disjunction, so a violation names the step that was skipped.
    if not exists (select 1 from pg_constraint where conname = 'journeys_repeated_before_waiting') then
        alter table public.journeys add constraint journeys_repeated_before_waiting
            check (escalation_state <> 'check_in_repeated' or check_in_repeated_at is not null);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'journeys_contacts_before_waiting') then
        alter table public.journeys add constraint journeys_contacts_before_waiting
            check (escalation_state <> 'contacts_notified' or contacts_notified_at is not null);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'journeys_sos_before_waiting') then
        alter table public.journeys add constraint journeys_sos_before_waiting
            check (escalation_state <> 'full_sos' or full_sos_at is not null);
    end if;
end $c$;


do $c$
begin
    -- The ordering invariant: no step without the one before it. These are the
    -- three rules that make "it cannot jump to panic" a property of the
    -- database rather than a property of one agent's SQL.
    --
    -- One-directional, like JG2's `journeys_asked_before_waiting`: a journey
    -- that escalated and was then answered returns to `normal` and KEEPS these
    -- timestamps, because they are the history of what happened on this trip.
    if not exists (select 1 from pg_constraint where conname = 'journeys_repeated_after_asked') then
        alter table public.journeys add constraint journeys_repeated_after_asked
            check (
                check_in_repeated_at is null
                or (check_in_sent_at is not null and check_in_repeated_at >= check_in_sent_at)
            );
    end if;

    if not exists (select 1 from pg_constraint where conname = 'journeys_contacts_after_repeated') then
        alter table public.journeys add constraint journeys_contacts_after_repeated
            check (
                contacts_notified_at is null
                or (check_in_repeated_at is not null
                    and contacts_notified_at >= check_in_repeated_at)
            );
    end if;

    if not exists (select 1 from pg_constraint where conname = 'journeys_sos_after_contacts') then
        alter table public.journeys add constraint journeys_sos_after_contacts
            check (
                full_sos_at is null
                or (contacts_notified_at is not null and full_sos_at >= contacts_notified_at)
            );
    end if;
end $c$;


do $c$
begin
    -- A position and its timestamp arrive together or not at all. A point with
    -- no time cannot be described honestly in an escalation email -- "last seen
    -- here" with no "when" is the kind of half-truth that sends somebody to the
    -- wrong place -- and a time with no point is a column that reads as though
    -- a position is known when none is.
    if not exists (select 1 from pg_constraint where conname = 'journeys_position_paired') then
        alter table public.journeys add constraint journeys_position_paired
            check ((last_position is null) = (last_position_at is null));
    end if;

    -- Nobody is told anything about a journey with no guardian. The app also
    -- declines to collect a position without one, and this is the backstop that
    -- makes that a guarantee rather than a convention.
    if not exists (select 1 from pg_constraint where conname = 'journeys_notice_needs_guardian') then
        alter table public.journeys add constraint journeys_notice_needs_guardian
            check (
                (started_notice_at is null and arrived_notice_at is null)
                or guardian_contact_id is not null
            );
    end if;
end $c$;


-- ---------------------------------------------------------------------------
-- The index the sweep needs
-- ---------------------------------------------------------------------------
-- `journey_watch` grows from two scans a minute to five, and three of the new
-- ones look up journeys by escalation state and the age of a timestamp. JG2's
-- `idx_journeys_due` covers only the deadline scan.
create index if not exists idx_journeys_escalating
    on public.journeys (escalation_state, check_in_sent_at)
    where state = 'active';


comment on column public.journeys.guardian_contact_id is
    'JG3. The one person told about this journey, chosen at start from '
    'emergency_contacts. NULL means nobody is told, which is a valid journey '
    'and not a degraded one -- see 20261015180000__journey_guardian.sql.';

comment on column public.journeys.last_position is
    'JG3. The last point the phone reported. Written by the heartbeat only when '
    'the journey has a guardian, and read only by an escalation message -- never '
    'by the started or arrived notices. One point, overwritten; not a log.';

comment on column public.journeys.escalation_state is
    'JG2/JG3. normal -> check_in_sent -> check_in_repeated -> contacts_notified '
    '-> full_sos, and back to normal on an answer from any state. Every forward '
    'step requires the previous step''s timestamp, enforced by CHECK.';
