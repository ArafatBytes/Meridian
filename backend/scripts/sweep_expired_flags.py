#!/usr/bin/env python3
"""
Retire flags whose decay curve has run out. IMPLEMENTATION_PLAN.md S20.

    python backend/scripts/sweep_expired_flags.py            retire them
    python backend/scripts/sweep_expired_flags.py --dry-run   count them, change nothing
    python backend/scripts/sweep_expired_flags.py --sql       print the SQL instead

The concept document's §6 promise is "no manual cleanup, no stale red zone". This is
the no-manual-cleanup half.

**The sweep deletes; it does not decide.**
----------------------------------------
That distinction is the whole design. Whether a flag is served is decided on read, by
comparing the stored `expires_at` against the instant being asked about — in SQL for
`DbRiskSurface`, in Python for `SeededRiskSurface`. A flag past its expiry stops being
served the moment it passes, whether or not this script has ever run.

So this is housekeeping, not enforcement, and that is deliberate. A cron job that
*decided* what is live would mean the surface was only correct as often as the job ran:
miss a night and the map shows stale red zones; run it at the wrong moment during a
rehearsal and flags vanish early. Making it housekeeping means the worst case for the
sweep never running is a table that grows, which is a cost problem rather than a
correctness one.

What it does, exactly: `status` becomes `expired` for live rows whose `expires_at` has
passed. Rows are not DELETEd. An expired flag is the evidence that the surface retires
things on its own, which is demo beat 5's claim, and throwing it away would make that
claim unverifiable the next morning.

Why it is not a Celery beat yet
-------------------------------
There is no Celery worker in `docker-compose.yml` and the beat schedule still points at
two modules that do not exist; D04 builds the schedule registry and is the first sprint
that actually needs a worker. Registering this task against a broken schedule now would
mean a task that looks scheduled and never runs — worse than a script somebody runs.
When D04 lands the registry, `sweep_expired()` below is the function to register.
"""

from __future__ import annotations

import argparse
import asyncio
import re
import sys
from pathlib import Path

for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    except (AttributeError, OSError):
        pass

BACKEND_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND_DIR))
sys.path.insert(0, str(BACKEND_DIR / "scripts"))

from migrate import connect  # noqa: E402

LIVE_STATUSES = ("unconfirmed", "confirmed")

COUNT_SQL = """
select count(*)
from public.risk_flags
where status = any($1::text[])
  and expires_at <= now()
"""

SWEEP_SQL = """
update public.risk_flags
   set status = 'expired'
 where status = any($1::text[])
   and expires_at <= now()
"""

STANDALONE_SQL = """-- ===========================================================================
-- Meridian — retire expired risk flags
-- ===========================================================================
-- Generated by backend/scripts/sweep_expired_flags.py.
--
-- Housekeeping only. A flag past expires_at already stops being served on read;
-- this is what stops the table growing without bound. See the script's docstring.
-- ===========================================================================

update public.risk_flags
   set status = 'expired'
 where status in ('unconfirmed', 'confirmed')
   and expires_at <= now();

-- What the surface looks like afterwards.
select status, count(*) as flags
from public.risk_flags
group by status
order by status;
"""


async def sweep_expired(*, dry_run: bool = False) -> int:
    """
    Retire every live flag past its expiry. Returns how many were (or would be) retired.

    Importable: this is the function D04's schedule registry should register, so the
    scheduled path and the manual path cannot drift.
    """
    conn = await connect()
    try:
        due = await conn.fetchval(COUNT_SQL, list(LIVE_STATUSES))
        if dry_run:
            print(f"  {due} flag(s) past expires_at would be retired")
            return int(due or 0)

        if not due:
            print("  nothing to retire")
            return 0

        result = await conn.execute(SWEEP_SQL, list(LIVE_STATUSES))
        match = re.search(r"(\d+)$", result or "")
        swept = int(match.group(1)) if match else int(due)
        print(f"  retired {swept} flag(s)")

        for row in await conn.fetch(
            "select status, count(*) as flags from public.risk_flags "
            "group by status order by status"
        ):
            print(f"    {row['status']:14s} {row['flags']}")
        return swept
    finally:
        await conn.close()


def main() -> int:
    parser = argparse.ArgumentParser(
        prog="sweep_expired_flags.py",
        description="Set status='expired' on risk flags past their expires_at.",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="report the count and change nothing"
    )
    parser.add_argument(
        "--sql",
        action="store_true",
        help="print paste-ready SQL instead of connecting (psql is not installed here)",
    )
    args = parser.parse_args()

    if args.sql:
        print(STANDALONE_SQL)
        return 0

    print("\nsweeping expired risk flags")
    asyncio.run(sweep_expired(dry_run=args.dry_run))
    print("  done\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
