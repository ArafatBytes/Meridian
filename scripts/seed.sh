#!/usr/bin/env bash
# =============================================================================
# Meridian — Prototype Gate check 2
# =============================================================================
# Bring a database up to the current schema and load the development fixtures.
#
#   ./scripts/seed.sh            baseline + migrations + fixtures + verify
#   ./scripts/seed.sh --fresh    RESET.sql first — DESTROYS ALL APPLICATION DATA
#   ./scripts/seed.sh --verify   run VERIFY.sql only, change nothing
#   ./scripts/seed.sh --no-data  schema only, no fixtures
#   ./scripts/seed.sh --sql      write everything to one file to paste by hand
#
# Four steps, in order:
#
#   1. BASELINE   backend/migrations/supabase/SCHEMA.sql — the tables the
#                 inherited app needs. Idempotent, applied whole, not versioned.
#                 It predates the migration runner and stays the starting point.
#   2. MIGRATIONS backend/migrations/versions/*.sql through scripts/migrate.py.
#                 Forward-only, checksummed, recorded in schema_migrations.
#                 Everything from D01 onward lives here.
#   3. FIXTURES   backend/scripts/seed_risk_flags.py — ~210 Dhaka risk flags.
#                 Flag text is generated by app/policy/framing.py at load time;
#                 the fixture file contains no prose.
#   4. VERIFY     VERIFY.sql, plus a row count on risk_flags.
#
# Needs python for steps 2 and 3, and psql for steps 1 and 4. Missing either, it
# tells you what to paste by hand and exits 0 — this script is a convenience, not
# the source of truth.
#
# If your database refuses direct connections, `--sql` writes one file containing
# all of it, ready for the Supabase SQL Editor.
# =============================================================================
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SQL_DIR="$ROOT/backend/migrations/supabase"
BACKEND="$ROOT/backend"

MODE=apply
WITH_DATA=1
for arg in "$@"; do
  case "$arg" in
    --fresh)   MODE=fresh ;;
    --verify)  MODE=verify ;;
    --sql)     MODE=sql ;;
    --no-data) WITH_DATA=0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

bold() { printf '\n\033[1m%s\033[0m\n' "$1"; }
ok()   { printf '  \033[32m✓\033[0m %s\n' "$1"; }
warn() { printf '  \033[33m-\033[0m %s\n' "$1"; }
bad()  { printf '  \033[31m✗\033[0m %s\n' "$1"; }

# Prefer the project venv so the fixture loader runs against the pinned
# interpreter rather than whatever `python` happens to mean today.
PY=""
for candidate in "$BACKEND/venv/Scripts/python.exe" "$BACKEND/venv/bin/python" python3 python; do
  if [ -x "$candidate" ] || command -v "$candidate" >/dev/null 2>&1; then PY="$candidate"; break; fi
done

# ---------------------------------------------------------------------------
# --sql: produce one paste-ready file and stop
# ---------------------------------------------------------------------------
if [ "$MODE" = sql ]; then
  bold "writing SQL for manual application"
  if [ -z "$PY" ]; then bad "no python interpreter found"; exit 1; fi

  OUT_DIR="$ROOT/.seed-sql"
  mkdir -p "$OUT_DIR"

  cp "$SQL_DIR/SCHEMA.sql" "$OUT_DIR/1-schema.sql"
  ok "1-schema.sql     (baseline tables)"

  "$PY" "$BACKEND/scripts/migrate.py" sql --out "$OUT_DIR/2-migrations.sql" >/dev/null \
    && ok "2-migrations.sql (risk_flags, ingestion, agent_runs)" \
    || { bad "could not generate migrations SQL"; exit 1; }

  if [ "$WITH_DATA" -eq 1 ]; then
    "$PY" "$BACKEND/scripts/seed_risk_flags.py" --sql --out "$OUT_DIR/3-fixtures.sql" >/dev/null \
      && ok "3-fixtures.sql   (~210 Dhaka risk flags)" \
      || { bad "could not generate fixture SQL"; exit 1; }
  fi

  cp "$SQL_DIR/VERIFY.sql" "$OUT_DIR/4-verify.sql"
  ok "4-verify.sql     (every row should read OK)"

  printf '\n  Open the Supabase dashboard → SQL Editor and run these in order:\n\n'
  for f in "$OUT_DIR"/*.sql; do printf '      %s\n' "$f"; done
  printf '\n  Fixture times are relative to now, so regenerate 3-fixtures.sql\n'
  printf '  rather than re-running an old copy.\n\n'
  exit 0
fi

bold "database"

# Pull DATABASE_URL out of backend/.env without sourcing the file (it contains
# values with spaces and '#' that a naive `source` would mangle).
DB_URL="${DATABASE_URL:-}"
if [ -z "$DB_URL" ] && [ -f "$BACKEND/.env" ]; then
  DB_URL="$(grep -E '^DATABASE_URL=' "$BACKEND/.env" | tail -1 | cut -d= -f2- | tr -d '"'"'"'' | xargs || true)"
fi

manual_instructions() {
  cat <<EOF

  Apply it by hand instead:

      ./scripts/seed.sh --sql

  writes numbered files to .seed-sql/ to paste into the Supabase SQL Editor.
  Full guide: backend/migrations/supabase/README.md

EOF
}

if [ -z "$DB_URL" ]; then
  warn "DATABASE_URL not set (checked the environment and backend/.env)"
  manual_instructions
  exit 0
fi

if ! command -v psql >/dev/null 2>&1; then
  warn "psql not on PATH"
  manual_instructions
  exit 0
fi

# psql speaks libpq, not SQLAlchemy. Strip the +asyncpg driver suffix.
PSQL_URL="${DB_URL/+asyncpg/}"

apply() {
  local file="$1"
  printf '  applying %s ... ' "$(basename "$file")"
  if psql "$PSQL_URL" --quiet --no-psqlrc -v ON_ERROR_STOP=1 -f "$file" >/tmp/meridian-seed.$$ 2>&1; then
    printf '\033[32mok\033[0m\n'
  else
    printf '\033[31mFAILED\033[0m\n'
    sed 's/^/      /' /tmp/meridian-seed.$$ | tail -30
    rm -f /tmp/meridian-seed.$$
    exit 1
  fi
  rm -f /tmp/meridian-seed.$$
}

# ---------------------------------------------------------------------------
# 0. --fresh
# ---------------------------------------------------------------------------
if [ "$MODE" = fresh ]; then
  printf '\n  \033[31m⚠  --fresh DESTROYS ALL APPLICATION DATA in this database.\033[0m\n'
  printf '     Target: %s\n' "$(echo "$PSQL_URL" | sed -E 's#//[^@]*@#//***@#')"
  printf '     Type "destroy" to continue: '
  read -r confirm
  [ "$confirm" = "destroy" ] || { echo "  aborted"; exit 1; }
  apply "$SQL_DIR/RESET.sql"
fi

# ---------------------------------------------------------------------------
# 1 + 2. baseline, then versioned migrations
# ---------------------------------------------------------------------------
if [ "$MODE" != verify ]; then
  apply "$SQL_DIR/SCHEMA.sql"

  bold "migrations"
  if [ -z "$PY" ]; then
    warn "no python interpreter — cannot run scripts/migrate.py"
    warn "the versioned migrations (risk_flags, ingestion, agent_runs) were NOT applied"
    manual_instructions
    exit 1
  fi
  "$PY" "$BACKEND/scripts/migrate.py" up || exit 1
fi

# ---------------------------------------------------------------------------
# 3. fixtures
# ---------------------------------------------------------------------------
if [ "$MODE" != verify ] && [ "$WITH_DATA" -eq 1 ]; then
  bold "fixtures"
  "$PY" "$BACKEND/scripts/seed_risk_flags.py" || exit 1
fi

# ---------------------------------------------------------------------------
# 4. verify
# ---------------------------------------------------------------------------
bold "verify"
psql "$PSQL_URL" --quiet --no-psqlrc -f "$SQL_DIR/VERIFY.sql"

# VERIFY.sql reports status in its result rows rather than via exit code, so scan
# the output for failures.
if psql "$PSQL_URL" --quiet --no-psqlrc -t -f "$SQL_DIR/VERIFY.sql" 2>/dev/null | grep -qE 'MISSING|FAIL'; then
  printf '\n  \033[31m✗ verification found problems — see the rows above\033[0m\n\n'
  exit 1
fi

# The schema check above knows nothing about D01's tables, so ask directly. A
# green VERIFY.sql with an empty risk_flags table would still mean a blank map.
printf '\n'
psql "$PSQL_URL" --quiet --no-psqlrc -c "
select 'risk_flags' as table,
       count(*) as rows,
       count(*) filter (where expires_at > now()) as live_now
from public.risk_flags;" 2>/dev/null || warn "risk_flags not present — did the migrations run?"

printf '\n  \033[32m✓ schema verified\033[0m\n\n'
